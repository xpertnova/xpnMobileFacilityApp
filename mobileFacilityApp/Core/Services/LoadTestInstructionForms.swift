import Foundation
import UIKit

/// The SAP master data the generated I3 forms are built from: the same
/// buildings, partners and plans their real forms offer.
struct LoadTestInstructionSource: Sendable {
    /// The SAP test address. Every generated I3 form names this partner, so
    /// a load test never puts a real company on a notification.
    static let testPartnerName = "Test Adresse für IT Zwecke"
    static let testPartnerFunction = "Z1"

    var contexts: [SafetyFormContext] = []
    var partners: [SAPBriefingPartner] = []
    var templates: [SAPBriefingTemplate] = []
    var workerProfile: SAPWorkerProfile?
    var workerName = ""

    @MainActor
    static func make(for workspace: FacilityDemoViewModel) -> Self {
        Self(
            contexts: SafetyFormContext.buildings(in: workspace.functionalLocationDirectory),
            partners: workspace.sapDataStore.cachedData.briefingPartners,
            templates: workspace.sapDataStore.cachedData.briefingTemplates,
            workerProfile: workspace.sapDataStore.workerProfile,
            workerName: workspace.effectiveWorkerDisplayName
        )
    }

    /// The test address, under its `Z1` function when the cache has it there.
    var testPartner: SAPBriefingPartner? {
        let matches = partners.filter {
            $0.name.trimmingCharacters(in: .whitespacesAndNewlines)
                .caseInsensitiveCompare(Self.testPartnerName) == .orderedSame
        }
        return matches.first { $0.function.caseInsensitiveCompare(Self.testPartnerFunction) == .orderedSame }
            ?? matches.first
    }

    var briefingTemplate: SAPBriefingTemplate? { templates.first(where: \.isStandardBriefing) }
    var qualificationTemplate: SAPBriefingTemplate? { templates.first(where: \.isQualificationTemplate) }

    var instructorFirstName: String { workerProfile?.firstName.nonEmpty ?? workerName.nameParts.first }
    var instructorLastName: String { workerProfile?.lastName.nonEmpty ?? workerName.nameParts.last }
    var organizationUnit: String { workerProfile?.organizationUnit ?? "" }

    var safetyFormSource: SafetyFormSource {
        SafetyFormSource(
            contexts: contexts,
            partners: testPartner.map { [$0] } ?? [],
            instructorFirstName: instructorFirstName,
            instructorLastName: instructorLastName,
            organizationUnit: organizationUnit
        )
    }
}

/// Builds the four I3 instruction forms for the load test seeder: briefing,
/// proof of qualification, electrical safety and fire permit. Each is filled
/// as far as its form demands before it may be closed; closing renders the
/// report with the form's own renderer, which is what goes to SAP.
@MainActor
enum LoadTestInstructionForms {
    /// One stroke standing in for every signature.
    static let signaturePNG: Data = UIGraphicsImageRenderer(size: CGSize(width: 300, height: 100)).pngData { _ in
        let path = UIBezierPath()
        path.move(to: CGPoint(x: 20, y: 70))
        path.addCurve(
            to: CGPoint(x: 280, y: 40),
            controlPoint1: CGPoint(x: 90, y: 0),
            controlPoint2: CGPoint(x: 180, y: 110)
        )
        path.lineWidth = 3
        UIColor.black.setStroke()
        path.stroke()
    }

    /// The legacy instructed-person field takes 29 characters.
    private static func person(_ label: String) -> String {
        String("\(LoadTestSeeder.marker) \(label)".prefix(29))
    }

    private static func task(_ label: String) -> String {
        "\(LoadTestSeeder.marker) \(label). Generated by the load test panel."
    }

    private static func coordinator(_ source: LoadTestInstructionSource) -> String {
        [source.instructorFirstName, source.instructorLastName]
            .filter { !$0.isEmpty }
            .joined(separator: " ")
            .nonEmpty ?? LoadTestSeeder.marker
    }

    /// "Ja" where a position offers it, so a closed form also sends the
    /// standard documents its positions point at.
    private static func answers(for sections: [SAPBriefingTemplateSection]) -> [String: String] {
        sections.flatMap(\.items).reduce(into: [:]) { answers, item in
            let option = item.answerOptions.first(where: \.isAffirmativeBriefingAnswer) ?? item.answerOptions.first
            if let option { answers[item.id] = option.key }
        }
    }

    // MARK: - Briefing

    static func briefing(
        label: String,
        context: SafetyFormContext,
        partner: SAPBriefingPartner,
        template: SAPBriefingTemplate,
        source: LoadTestInstructionSource,
        now: Date = .now
    ) -> BriefingDraftPayload {
        BriefingDraftPayload(
            templateID: template.id,
            businessEntityID: context.businessEntityID,
            businessEntityTitle: context.businessEntityTitle,
            buildingCode: context.buildingCode,
            buildingTitle: context.buildingTitle,
            coordinator: coordinator(source),
            instructedPerson: person(label),
            selectedPartnerID: partner.id,
            temporaryPartner: nil,
            partnerEmail: partner.email,
            taskDescription: task(label),
            startDate: now,
            endDate: now,
            selectedOptionalSectionIDs: [],
            answerKeysByItemID: answers(for: template.sections.filter { !$0.isOptional }),
            commentsByItemID: [:],
            instructorSignature: signaturePNG,
            instructedPersonSignature: signaturePNG,
            completedAt: nil
        )
    }

    /// Goes through the form's own view model, so the report is the one the
    /// technician would get for this draft.
    static func closed(
        _ draft: BriefingDraftPayload,
        source: LoadTestInstructionSource,
        offlineWorkStore: OfflineWorkStore
    ) async throws -> BriefingDraftPayload {
        let model = BriefingWorkflowViewModel(
            source: .init(
                isDemo: false,
                contexts: [.init(
                    businessEntityID: draft.businessEntityID,
                    businessEntityTitle: draft.businessEntityTitle,
                    buildingCode: draft.buildingCode,
                    buildingTitle: draft.buildingTitle
                )],
                partners: source.partners,
                templates: source.templates,
                workerProfile: source.workerProfile,
                workerName: source.workerName,
                offlineWorkStore: offlineWorkStore
            ),
            existingDraft: temporaryItem(.briefing, .briefing(draft), offlineWorkStore)
        )
        guard let template = model.template, let payload = model.makePDFPayload() else {
            throw LoadTestSeederError.reportFailed
        }
        let artifact = await Task.detached(priority: .userInitiated) {
            try? LegacyBriefingPDFRenderer().render(payload)
        }.value
        guard let artifact else { throw LoadTestSeederError.reportFailed }

        var closed = draft
        closed.completedAt = artifact.createdAt
        closed.pdfData = artifact.data
        closed.additionalDocumentSymbolIDs = InstructionFormReferenceDocuments.symbolIDs(
            sections: template.sections,
            answerKeysByItemID: draft.answerKeysByItemID,
            selectedOptionalSectionIDs: draft.selectedOptionalSectionIDs
        )
        return closed
    }

    // MARK: - Proof of qualification

    static func qualification(
        label: String,
        context: SafetyFormContext,
        partner: SAPBriefingPartner,
        template: SAPBriefingTemplate,
        source: LoadTestInstructionSource,
        now: Date = .now
    ) -> ProofOfQualificationDraftPayload {
        ProofOfQualificationDraftPayload(
            template: template,
            context: context,
            instructorFirstName: source.instructorFirstName,
            instructorLastName: source.instructorLastName,
            organizationUnit: source.organizationUnit,
            contactPerson: person(label),
            coordinator: coordinator(source),
            partner: partner,
            partnerEmail: partner.email,
            workLocation: context.functionalLocationTitle,
            taskDescription: task(label),
            executionStart: now,
            executionEnd: now,
            answerKeysByItemID: answers(for: template.sections),
            commentsByItemID: [:],
            coordinatorSignature: signaturePNG,
            instructedPersonSignature: signaturePNG,
            pdfData: nil,
            completedAt: nil
        )
    }

    static func closed(
        _ draft: ProofOfQualificationDraftPayload,
        offlineWorkStore: OfflineWorkStore
    ) async throws -> ProofOfQualificationDraftPayload {
        let model = ProofOfQualificationViewModel(
            source: ProofOfQualificationSource(
                isDemo: false,
                contexts: draft.context.map { [$0] } ?? [],
                partners: draft.partner.map { [$0] } ?? [],
                template: draft.template,
                instructorFirstName: draft.instructorFirstName,
                instructorLastName: draft.instructorLastName,
                organizationUnit: draft.organizationUnit
            ),
            existingDraft: temporaryItem(.proofOfQualification, .proofOfQualification(draft), offlineWorkStore)
        )
        guard let payload = model.makePDFPayload() else { throw LoadTestSeederError.reportFailed }
        let artifact = await Task.detached(priority: .userInitiated) {
            try? ProofOfQualificationPDFRenderer().render(payload)
        }.value
        guard let artifact else { throw LoadTestSeederError.reportFailed }

        var closed = draft
        closed.completedAt = artifact.createdAt
        closed.pdfData = artifact.data
        closed.additionalDocumentSymbolIDs = InstructionFormReferenceDocuments.symbolIDs(
            sections: draft.template.sections,
            answerKeysByItemID: draft.answerKeysByItemID
        )
        return closed
    }

    // MARK: - Electrical safety

    static func electricalSafety(
        label: String,
        context: SafetyFormContext,
        partner: SAPBriefingPartner,
        source: LoadTestInstructionSource,
        now: Date = .now
    ) -> ElectricalSafetyDraftPayload {
        let name = coordinator(source)
        var draft = ElectricalSafetyDraftPayload(source: source.safetyFormSource, now: now)
        draft.context = context
        draft.instructedPerson = person(label)
        draft.partner = partner
        draft.partnerEmail = partner.email
        draft.coordinator = name
        draft.workDescription = task(label)
        draft.workplace = context.buildingTitle
        draft.electricalWork = LoadTestSeeder.marker
        draft.systemResponsible.name = name
        draft.workResponsible.name = person(label)
        draft.workDeEnergized = true
        draft.instructedWorkResponsible = true
        for slot in ElectricalSafetySignatureSlot.allCases {
            let signer: String
            switch slot {
            case .handoverSystemResponsible, .returnSystemResponsible: signer = draft.systemResponsible.name
            case .handoverWorkResponsible, .returnWorkResponsible: signer = draft.workResponsible.name
            }
            draft.signatures[slot] = SafetyFormSignature(signerName: signer, capturedAt: now, pngData: signaturePNG)
        }
        return draft
    }

    static func closed(_ draft: ElectricalSafetyDraftPayload) async throws -> ElectricalSafetyDraftPayload {
        let artifact = await Task.detached(priority: .userInitiated) {
            try? LegacyElectricalSafetyPDFRenderer().render(draft)
        }.value
        guard let artifact else { throw LoadTestSeederError.reportFailed }
        var closed = draft
        closed.completedAt = artifact.createdAt
        closed.pdfData = artifact.data
        return closed
    }

    // MARK: - Fire permit

    /// A fire permit exists only closed: its form keeps no draft.
    static func firePermit(
        label: String,
        context: SafetyFormContext,
        partner: SAPBriefingPartner,
        source: LoadTestInstructionSource,
        now: Date = .now
    ) async throws -> FirePermitDraftPayload {
        let name = coordinator(source)
        var record = FirePermitRecord(source: source.safetyFormSource, now: now)
        record.context = context
        record.instructedPerson = person(label)
        record.partner = partner
        record.partnerEmail = partner.email
        record.coordinator = name
        record.workDescription = task(label)
        record.workTypes = [.grinding]
        record.measures[.removeCombustibles] = true
        record.measures[.fireWatchDuringWork] = true
        record.fireHazardPerformer = name
        record.extinguishingPerformer = name
        record.fireAlarmPerformer = name
        record.explosionPerformer = name
        record.permitIssuerName = name
        record.contractorName = person(label)
        record.onSiteWorkerName = person(label)
        record.fireWatchName = person(label)
        for slot in FirePermitSignatureSlot.allCases {
            let signer = slot == .contractor || slot == .onSiteWorker ? person(label) : name
            record.signatures[slot] = SafetyFormSignature(signerName: signer, capturedAt: now, pngData: signaturePNG)
        }

        let snapshot = record
        let artifact = await Task.detached(priority: .userInitiated) {
            try? LegacyFirePermitPDFRenderer().render(snapshot)
        }.value
        guard let artifact else { throw LoadTestSeederError.reportFailed }
        return FirePermitDraftPayload(
            context: record.context,
            instructedPerson: record.instructedPerson,
            partner: record.partner,
            partnerEmail: record.partnerEmail,
            coordinator: record.coordinator,
            workDescription: record.workDescription,
            executionStart: record.executionStart,
            executionEnd: record.executionEnd,
            pdfData: artifact.data,
            completedAt: artifact.createdAt
        )
    }

    /// Never saved: only what a form's view model restores its fields from.
    private static func temporaryItem(
        _ type: OfflineWorkType,
        _ payload: OfflineWorkPayload,
        _ offlineWorkStore: OfflineWorkStore
    ) -> OfflineWorkItem {
        OfflineWorkItem(
            id: UUID(), workerID: offlineWorkStore.workerID, type: type, status: .draft,
            payload: payload, createdAt: .now, updatedAt: .now, syncError: nil
        )
    }
}
