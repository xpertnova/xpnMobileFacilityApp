#!/usr/bin/env node

const crypto = require("crypto");
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const repositoryRoot = path.resolve(__dirname, "..");
const sourceRoot = path.resolve(process.argv[2] || "/Users/simenn/ios/www/edata");
const sourceFiles = ["createTypes.js", "create.js"];
const sources = Object.fromEntries(sourceFiles.map(name => [
  name,
  fs.readFileSync(path.join(sourceRoot, name), "utf8")
]));

const context = vm.createContext({
  edata: {},
  cloneObject(value) { return JSON.parse(JSON.stringify(value)); },
  jQuery: { sap: { declare() {} } }
});
vm.runInContext(
  'String.prototype.format = function(){var a=arguments;return this.replace(/{(\\d+)}/g,function(m,n){return typeof a[n]!=="undefined"?a[n]:m;});};',
  context
);
for (const name of sourceFiles) vm.runInContext(sources[name], context, { filename: name });

const statements = [];
context.edata.create.createAllTbl({ executeSql(sql) { statements.push(sql); } });

function parseCreateTable(sql) {
  const match = sql.match(/^CREATE\s+TABLE\s+IF\s+NOT\s+EXISTS\s+([^\s(]+)\s*\((.*)\)\s*$/is);
  if (!match) throw new Error(`Unsupported CREATE TABLE statement: ${sql}`);
  const name = match[1].trim().toUpperCase();
  const columns = match[2].split(",").map(fragment => {
    const column = fragment.trim().match(/^([^\s]+)\s+(.+)$/s);
    if (!column) throw new Error(`Unsupported column in ${name}: ${fragment}`);
    return { name: column[1].toUpperCase(), type: column[2].trim().toUpperCase() };
  });
  return { name, columns };
}

const excludedPattern = /(?:^|_)T025\d/;
const tables = statements.map(parseCreateTable).filter(table => !excludedPattern.test(table.name));
const categories = {
  FROM: tables.filter(table => table.name.startsWith("FROM_")),
  TO: tables.filter(table => table.name.startsWith("TO_")),
  TMP_FROM: tables.filter(table => table.name.startsWith("TMP_FROM_")),
  TMP_TO: tables.filter(table => table.name.startsWith("TMP_TO_")),
  SUPPORT: tables.filter(table => !/^(?:FROM_|TO_|TMP_FROM_|TMP_TO_)/.test(table.name))
};
const expected = { FROM: 22, TO: 18, TMP_FROM: 22, TMP_TO: 18, SUPPORT: 6 };
for (const [category, count] of Object.entries(expected)) {
  if (categories[category].length !== count) {
    throw new Error(`${category}: expected ${count}, found ${categories[category].length}`);
  }
}
if (tables.length !== 86) throw new Error(`Expected 86 tables, found ${tables.length}`);
if (new Set(tables.map(table => table.name)).size !== tables.length) throw new Error("Duplicate table name");

const sourceHashes = Object.fromEntries(sourceFiles.map(name => [
  name,
  crypto.createHash("sha256").update(sources[name]).digest("hex")
]));
const manifest = {
  source: sourceRoot,
  sourceHashes,
  excludedTablePattern: "(?:^|_)T025\\d",
  counts: Object.fromEntries(Object.entries(categories).map(([name, rows]) => [name, rows.length])),
  tables
};

function swiftString(value) {
  return JSON.stringify(value).replace(/\\u2028|\\u2029/g, value => value === "\\u2028" ? "\\u{2028}" : "\\u{2029}");
}
const tableLines = tables.map(table => {
  const columns = table.columns.map(column =>
    `.init(name: ${swiftString(column.name)}, declaredType: ${swiftString(column.type)})`
  ).join(", ");
  return `        .init(name: ${swiftString(table.name)}, columns: [${columns}])`;
}).join(",\n");
const swift = `// Generated by scripts/generate-legacy-schema.js from the editable Cordova source.\n` +
`// createTypes.js SHA-256: ${sourceHashes["createTypes.js"]}\n` +
`// create.js SHA-256: ${sourceHashes["create.js"]}\n` +
`// Do not edit by hand.\n\n` +
`import Foundation\n\n` +
`struct LegacySQLiteColumn: Equatable, Sendable {\n    let name: String\n    let declaredType: String\n}\n\n` +
`struct LegacySQLiteTable: Equatable, Sendable {\n    let name: String\n    let columns: [LegacySQLiteColumn]\n\n` +
`    var createSQL: String {\n        let definitions = columns.map { \"\\($0.name) \\($0.declaredType)\" }.joined(separator: \", \" )\n        return \"CREATE TABLE IF NOT EXISTS \\(name) ( \\(definitions) )\"\n    }\n}\n\n` +
`enum LegacySQLiteSchema {\n    static let databaseFileName = \"mtfm.db\"\n    static let appDatabaseVersion = \"358\"\n    static let tables: [LegacySQLiteTable] = [\n${tableLines}\n    ]\n\n` +
`    static let byName = Dictionary(uniqueKeysWithValues: tables.map { ($0.name, $0) })\n` +
`    static let permanentInbound = tables.filter { $0.name.hasPrefix(\"FROM_\") }\n` +
`    static let temporaryInbound = tables.filter { $0.name.hasPrefix(\"TMP_FROM_\") }\n` +
`    static let permanentOutgoing = tables.filter { $0.name.hasPrefix(\"TO_\") }\n` +
`    static let temporaryOutgoing = tables.filter { $0.name.hasPrefix(\"TMP_TO_\") }\n}\n`;

const swiftPath = path.join(repositoryRoot, "mobileFacilityApp/Core/Database/LegacySQLiteSchema.generated.swift");
const manifestDirectory = path.join(repositoryRoot, "mobileFacilityAppTests/Fixtures");
fs.mkdirSync(path.dirname(swiftPath), { recursive: true });
fs.mkdirSync(manifestDirectory, { recursive: true });
fs.writeFileSync(swiftPath, swift);
fs.writeFileSync(path.join(manifestDirectory, "legacy-schema.json"), JSON.stringify(manifest, null, 2) + "\n");
console.log(`Generated ${tables.length} tables (${Object.entries(expected).map(([key, count]) => `${key}=${count}`).join(", ")})`);
